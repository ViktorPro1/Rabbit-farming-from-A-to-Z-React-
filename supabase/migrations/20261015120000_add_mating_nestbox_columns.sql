-- Міграція: маточник і повторна злучка на рівні злучки (таблиця matings).
-- Поки в злучки немає окролів, кнопки «Маточник підготовлено» та
-- «Покрилась повторно» працюють із цими колонками. Після додавання окролу
-- ті самі дані ведуться в таблиці litters (як і раніше).

-- Дата, коли підготовлено маточник
alter table public.matings
  add column if not exists nestbox_date date;

-- Дата попередньої (невдалої) спроби злучки — заповнюється при «Покрилась повторно»
alter table public.matings
  add column if not exists previous_mating_date date;
